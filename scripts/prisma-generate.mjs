/**
 * Generates both Prisma clients:
 *   - SQLite   -> src/generated/prisma     (running on your own computer, and the test suite)
 *   - Postgres -> src/generated/prisma-pg  (hosted use, e.g. Vercel + Neon)
 *
 * prisma/schema.prisma is the single source of truth. The Postgres schema is derived from it on every
 * run (only the provider and the output folder differ), so the two can never drift apart.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sqliteSchema = path.join(root, "prisma", "schema.prisma");
const pgDir = path.join(root, "prisma", "postgres");
const pgSchema = path.join(pgDir, "schema.prisma");

const source = fs.readFileSync(sqliteSchema, "utf8");
if (!/provider\s*=\s*"sqlite"/.test(source) || !/output\s*=\s*"\.\.\/src\/generated\/prisma"/.test(source)) {
  throw new Error("prisma/schema.prisma no longer has the sqlite datasource / generator output this script rewrites.");
}

const derived = source
  .replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"')
  .replace(/output\s*=\s*"\.\.\/src\/generated\/prisma"/, 'output   = "../../src/generated/prisma-pg"');

fs.mkdirSync(pgDir, { recursive: true });
fs.writeFileSync(
  pgSchema,
  `// GENERATED by scripts/prisma-generate.mjs from ../schema.prisma. Do not edit: change schema.prisma instead.\n${derived}`,
);

const prisma = path.join(root, "node_modules", ".bin", "prisma");
for (const schema of [sqliteSchema, pgSchema]) {
  execFileSync(prisma, ["generate", "--schema", schema], { stdio: "inherit", cwd: root });
}
